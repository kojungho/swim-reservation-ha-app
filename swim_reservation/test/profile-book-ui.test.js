import {chooseSites,availableSiteChoices} from "./fixtures/ui-book-app.js";
import { openPlanDetails } from "./fixtures/ui-book-app.js";
import test from "node:test";
import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { chromium } from "playwright-core";
import { mockBookApp, testGuest } from "./fixtures/ui-book-app.js";

const executablePath = [process.env.CHROMIUM_PATH, "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", "/usr/bin/chromium"].filter(Boolean).find(existsSync);
test("PC·폰의 저장 예약자는 자동 목록만 표시하고 사람별 선택·신규 저장·일정 초안 유지가 독립적이다", { skip: !executablePath }, async t => {
  const browser = await chromium.launch({ executablePath, headless: true });
  t.after(() => browser.close());
  for (const width of [1280, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 844 } });
    const state = await mockBookApp(page);
    assert.equal(await page.locator("#reserverName").inputValue(), "");
    assert.equal(await page.locator("#loadProfilesButton").count(), 0);
    assert.equal(await page.locator("#monthlyButton").count(), 0);
    assert.equal(await page.locator("#saveProfilesButton").isDisabled(), true);
    for (const tab of ["priority", "multiple", "watch", "profiles-parallel"]) {
      await page.locator("#workspaceMenuButton").click();
      await page.locator('[data-workspace-tab="' + tab + '"]').click();
      assert.equal(await page.locator("#bookingProfileSelect1 option").count(), 3);
      assert.equal(await page.locator("#reserverName").inputValue(), "");
      assert.equal(await page.locator("#extraProfiles .second-profile-panel").count(), 0);
    }
    await page.locator("#bookingProfileSelect1").selectOption("0");
    assert.equal(await page.locator("#reserverName").inputValue(), testGuest(1).reserverName);
    assert.equal(await page.locator("#saveProfilesButton").isDisabled(), true);
    await page.locator("#addProfileButton").click();
    assert.equal(await page.locator("#profilePriorities .site-choice-row").count(), 0);
    assert.equal(await page.locator("#reserverName2").inputValue(), "");
    await page.locator("#bookingProfileSelect2").selectOption("1");
    assert.equal(await page.locator("#reserverName2").inputValue(), testGuest(2).reserverName);
    assert.equal(await page.locator("#saveBookingActor2").isDisabled(), true);
    await page.locator("#bookingProfileSelect2").selectOption("");
    const guest = testGuest(3);
    for (const [key, value] of Object.entries(guest).filter(([key]) => key !== 'birthDate')) await page.locator("#" + key + "2").fill(value);
    assert.equal(await page.locator("#saveBookingActor2").isEnabled(), true);
    await page.locator("#saveBookingActor2").click();
    await page.waitForFunction(() => document.querySelector("#bookingProfileSelect2").options.length === 4);
    assert.equal(state.book.length, 3);
    assert.equal(state.book[0].roomPriority.find(room => room.name === "달_하늘존").enabled, true);
    assert.equal(await page.locator("#saveBookingActor2").isDisabled(), true);
    await page.locator("#startDate").fill("2026-12-20");
    await chooseSites(page,'[data-profile-index="0"]',["해_하늘존"]);
    await chooseSites(page,'[data-profile-index="1"]',["달_하늘존"]);
    await page.locator("#planName").fill("사람별 일정");
    await page.locator("#addPlanButton").click();
    await page.locator("#executionPlanList .execution-plan").first().waitFor();
    assert.equal(state.plans[0].config.profiles.length, 2);
    assert.equal(state.plans[0].config.profiles[1].reserverName, guest.reserverName);
    await openPlanDetails(page);
    assert.deepEqual(await page.locator("#planList .plan-profile-targets p").allTextContents(), ["저장예약자1 : ① 해", "저장예약자3 : ① 달"]);
    await page.locator("#planDetailsClose").click();
    assert.equal(await page.locator("#reserverName").inputValue(), testGuest(1).reserverName);
    assert.equal(await page.locator("#extraProfiles .second-profile-panel").count(), 1);
    assert.equal(await page.locator("#bookingProfileSelect1").inputValue(), "0");
    assert.equal(state.book.length, 3);
    await openPlanDetails(page, 0);
    await page.locator("#planList .plan-entry").getByRole("button", { name: "설정 불러오기", exact: true }).click();
    await page.waitForFunction(() => document.querySelector("#reserverName2")?.value === "저장예약자3");
    await page.locator("#workspaceMenuButton").click();
    await page.locator('[data-workspace-tab="multiple"]').click();
    await page.locator("#bookingProfileSelect1").selectOption("2");
    assert.equal(await page.locator("#reserverName").inputValue(), guest.reserverName);
    assert.equal(await page.locator("#extraProfiles .second-profile-panel").count(), 0);
    await page.locator("#startDate").fill("2026-12-21");
    await page.locator("#startDate").fill("2026-12-20");
    await chooseSites(page);
    await page.evaluate(() => elements.saveButton.click());
    await page.waitForFunction(() => document.querySelector("#workspaceMessage").textContent.includes("설정을 HA"));
    assert.equal(state.book.length, 3);
    assert.equal(state.config.profiles.length, 1);
    assert.equal(state.config.profiles[0].reserverName, guest.reserverName);
    await page.reload();
    await page.waitForFunction(() => document.querySelector("#bookingProfileSelect1").options.length === 4);
    assert.equal(await page.locator("#reserverName").inputValue(), guest.reserverName);
    assert.equal(await page.locator("#extraProfiles .second-profile-panel").count(), 0);
    await page.locator("#workspaceMenuButton").click();
    await page.locator('[data-workspace-tab="profiles-parallel"]').click();
    await page.locator('#editorResetButton').click();
    await page.locator('#editorResetConfirm').click();
    for (let person = 2; person <= 5; person++) await page.locator("#addProfileButton").click();
    assert.equal(await page.locator("#addProfileButton").isDisabled(), false);
    await page.locator("#bookingProfileSelect5").selectOption("2");
    assert.equal(await page.locator("#reserverName5").inputValue(), guest.reserverName);
    await page.locator("#extraProfiles .second-profile-panel").nth(1).getByRole("button", { name: "예약자 제외", exact: true }).click();
    await page.locator('#profileRemoveConfirm').click();
    assert.equal(await page.locator("#reserverName4").inputValue(), guest.reserverName);
    assert.equal(await page.locator("#addProfileButton").isEnabled(), true);
    assert.deepEqual(state.errors, []);
    await page.close();
  }
});
